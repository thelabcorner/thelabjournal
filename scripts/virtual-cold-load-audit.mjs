import {chromium} from 'playwright-core'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']})
const context=await browser.newContext({viewport:{width:375,height:812},isMobile:true,hasTouch:true,serviceWorkers:'block'})
const page=await context.newPage()
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:11265/',{waitUntil:'networkidle'})
const resources=async()=>page.evaluate(()=>performance.getEntriesByType('resource').filter(x=>x.name.includes('/assets/')&&x.name.endsWith('.js')).map(x=>x.name.split('/').at(-1)))
const initial=await resources()
if(initial.some(x=>/Windowed|index-CCjqg/.test(x)))throw Error('virtualizer loaded on nine-entry initial journal '+initial)
const browse=page.getByRole('navigation',{name:'Mobile primary navigation'}).getByRole('button',{name:'Browse'})
await browse.click()
await page.getByRole('dialog',{name:'Journal navigation'}).getByRole('button',{name:'Recent writing'}).click()
await page.getByRole('button',{name:'Learning in reverse'}).count()
const recentCount=await page.locator('.browse-recent-list > button').count()
if(recentCount<1||recentCount>=24)throw Error('recent entry list unexpectedly empty or beyond virtual threshold '+recentCount)
const afterBrowse=await resources()
if(afterBrowse.some(x=>/Windowed|index-CCjqg/.test(x)))throw Error('virtualizer loaded unnecessarily for nine browse entries '+afterBrowse)
await page.getByRole('dialog',{name:'Journal navigation'}).getByRole('button',{name:'Close navigation'}).click()
await page.getByRole('navigation',{name:'Mobile primary navigation'}).getByRole('button',{name:'Search'}).click()
await page.getByRole('dialog',{name:'Search the journal'}).waitFor()
const searchCount=await page.locator('.spotlight-option').count()
if(searchCount<1||searchCount>9)throw Error('spotlight suggestions should remain deliberately bounded '+searchCount)
const afterSearch=await resources()
if(afterSearch.some(x=>/Windowed|index-CCjqg/.test(x)))throw Error('virtualizer loaded unnecessarily for nine search entries '+afterSearch)
if(errors.length)throw Error(JSON.stringify(errors))
console.log(JSON.stringify({pass:true,initial,afterBrowse,afterSearch,recentCount,searchCount}))
await context.close()
await browser.close()
