import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const origin=process.env.JOURNAL_ORIGIN??'http://localhost:11266/'
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH??'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']})
const vb=async svg=>(await svg.getAttribute('viewBox')).split(/[\s,]+/).map(Number)
try{
  for(const size of [{width:375,height:812},{width:320,height:568}]){
    const page=await browser.newPage({viewport:size,isMobile:true,hasTouch:true,serviceWorkers:'block',reducedMotion:'no-preference'})
    const errors=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.goto(origin+'quotes/',{waitUntil:'domcontentloaded'})
    const trigger=page.getByRole('button',{name:'Expand thought atlas to portrait view'})
    await trigger.click()
    const overlay=page.getByRole('dialog',{name:'Expanded thought atlas'})
    await overlay.waitFor()
    const svg=overlay.locator('svg.quotes-atlas-svg')
    const viewport=overlay.locator('.quotes-atlas-camera')
    const initial=await vb(svg)
    const box=await viewport.boundingBox()
    assert(box && box.width>200 && box.height>120)
    const cx=box.x+box.width/2,cy=box.y+box.height/2
    const cdp=await page.context().newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:cx-32,y:cy},{id:2,x:cx+32,y:cy}]})
    for(let n=1;n<=6;n++){
      await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[
        {id:1,x:cx-32-n*9,y:cy},{id:2,x:cx+32+n*9,y:cy}
      ]})
      await page.waitForTimeout(24)
    }
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await page.waitForTimeout(160)
    const pinched=await vb(svg)
    console.log('PINCH_STATE',size.width,JSON.stringify({selection:await overlay.locator('.quotes-atlas-node.is-selected').count(),height:await viewport.evaluate(e=>e.clientHeight)}))
    assert(pinched[2] < initial[2] * .82,'pinch should zoom using ZoomPort: '+initial+' -> '+pinched)
    const priorScroll=await page.evaluate(()=>scrollY)
    await page.mouse.move(cx,cy)
    await page.mouse.down()
    await page.mouse.move(cx+36,cy+27,{steps:8})
    await page.mouse.up()
    await page.waitForTimeout(140)
    const panned=await vb(svg)
    console.log('PAN_STATE',size.width,JSON.stringify({selection:await overlay.locator('.quotes-atlas-node.is-selected').count(),height:await viewport.evaluate(e=>e.clientHeight)}))
    const moved=Math.hypot(panned[0]-pinched[0],panned[1]-pinched[1])
    assert(moved>2,'drag should pan camera: '+pinched+' -> '+panned)
    assert.equal(await page.evaluate(()=>scrollY),priorScroll,'background scroll unchanged after drag/pinch')
    await overlay.getByRole('button',{name:'Fit entire atlas'}).click()
    await page.waitForTimeout(100)
    const reset=await vb(svg)
    console.log('FIT_DEBUG',size.width,JSON.stringify({initial,pinched,panned,reset}))
    assert(Math.abs(reset[2]-initial[2])<2,'Fit restores atlas framing')
    const graphNode=overlay.locator('.quotes-atlas-node').nth(24)
    await graphNode.click({force:true})
    const selected=overlay.locator('.quotes-atlas-node.is-selected')
    assert.equal(await selected.count(),1,'tap selects only a single node')
    const id=await selected.getAttribute('data-quote-id')
    assert.equal(new URL(page.url()).pathname,'/quotes/','node tap must not redirect')
    const read=overlay.getByRole('button',{name:'Read entry'})
    assert(await read.isVisible(),'inspect panel includes explicit read affordance')
    await read.click()
    await page.waitForTimeout(100)
    assert.equal(new URL(page.url()).pathname,'/quotes/'+id+'/','only Read entry navigates')
    assert.equal(await page.getByRole('dialog',{name:'Expanded thought atlas'}).count(),0,'overlay closes after reading')
    assert(errors.length===0,'browser errors: '+errors.join('; '))
    console.log('GESTURE_AND_INSPECTION_PASS',size.width+'x'+size.height,JSON.stringify({initial,pinched,panned,moved,selected:id}))
    await page.close()
  }
  const page=await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true,serviceWorkers:'block',reducedMotion:'reduce'})
  await page.goto(origin+'quotes/',{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Expand thought atlas to portrait view'}).click()
  const overlay=page.getByRole('dialog',{name:'Expanded thought atlas'})
  assert.equal(await overlay.locator('.quotes-atlas-current').evaluate(e=>getComputedStyle(e).display),'none','reduced motion hides moving signals')
  await page.locator('.mobile-tabbar').getByRole('button',{name:'Journal'}).click()
  await page.waitForTimeout(120)
  assert.equal(await overlay.count(),0,'bottom nav remains interactive and closes atlas via route transition')
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'','body scroll restored after route transition')
  console.log('REDUCED_MOTION_AND_BOTTOM_NAV_PASS')
  await page.close()
}finally{await browser.close()}
