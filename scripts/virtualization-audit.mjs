import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true,args:['--no-sandbox'] })
let failures=0
for(const width of [375,768,1440]) {
  const page=await browser.newPage({viewport:{width,height:width<768?812:900},isMobile:width<768,hasTouch:width<768})
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  try {
    await page.goto('http://127.0.0.1:11264/virtual-fixture.html',{waitUntil:'networkidle'})
    const list=page.locator('[data-virtualized="archive"]')
    await list.waitFor()
    await page.waitForTimeout(200)
    const metrics=async()=>list.evaluate(node=>{
      const indices=[...node.querySelectorAll('[data-fixture-index]')].map(n=>Number(n.getAttribute('data-fixture-index')))
      const rows=[...node.querySelectorAll('.windowed-archive-row')].map(n=>({top:n.getBoundingClientRect().top,bottom:n.getBoundingClientRect().bottom, height:n.getBoundingClientRect().height}))
      return {indices, count:indices.length, height:node.getBoundingClientRect().height, rows}
    })
    let top=await metrics()
    if(top.count<1||top.count>52||top.height<30000)throw Error('virtualization disabled or bad height at top '+JSON.stringify(top))
    await page.evaluate(()=>{
      const node=document.querySelector('[data-virtualized="archive"]')
      const start=node.getBoundingClientRect().top+window.scrollY
      window.scrollTo({top:start+32000,behavior:'instant'})
    })
    await page.waitForTimeout(320)
    let mid=await metrics()
    if(!mid.indices.length || Math.min(...mid.indices)<120||mid.count>52)throw Error('mid-scroll lost virtualization '+JSON.stringify(mid))
    if(mid.rows.some(r=>r.height<=0))throw Error('zero-height item')
    if(mid.rows.some((r,i)=>i>0 && r.top+1<mid.rows[i-1].bottom))throw Error('row overlap '+JSON.stringify(mid.rows))
    await page.getByRole('button',{name:'Toggle layout'}).click()
    await page.waitForTimeout(240)
    const cards=await metrics()
    if(cards.count<1||cards.count>52)throw Error('cards failed '+JSON.stringify(cards))
    if(width>767 && await list.locator('.windowed-archive-row--cards').first().locator('.windowed-archive-cell').count()!==2)throw Error('desktop should have 2 columns')
    if(width<=767 && await list.locator('.windowed-archive-row--cards').first().locator('.windowed-archive-cell').count()!==1)throw Error('mobile should have 1 column')
    await page.getByRole('button',{name:'Reverse order'}).click()
    await page.waitForTimeout(190)
    const reversed=await metrics()
    if(!reversed.indices.some(i=>i>1450))throw Error('sorting did not update first rows '+JSON.stringify(reversed.indices))
    await page.getByRole('button',{name:'Toggle count'}).click()
    await page.waitForTimeout(190)
    const reduced=await metrics()
    if(reduced.count>36)throw Error('reduced list too large')
    const pane=page.locator('[aria-label="Fixture search results"]')
    await pane.scrollIntoViewIfNeeded()
    await pane.evaluate(node=>{node.scrollTop=node.scrollHeight*.6;node.dispatchEvent(new Event('scroll'))})
    await page.waitForTimeout(140)
    const pCount=await pane.locator('[data-pane-index]').count()
    if(pCount>23||pCount<1)throw Error('search pane count '+pCount)
    const browse=page.locator('[aria-label="Fixture recent writing"]')
    await browse.scrollIntoViewIfNeeded()
    await browse.evaluate(node=>{node.scrollTop=node.scrollHeight*.75;node.dispatchEvent(new Event('scroll'))})
    await page.waitForTimeout(140)
    const bCount=await browse.locator('[data-browse-index]').count()
    if(bCount>22||bCount<1)throw Error('browse pane count '+bCount)
    if(errors.length)throw Error('browser errors '+JSON.stringify(errors))
    console.log(JSON.stringify({width,pass:true,top:{count:top.count,height:top.height},mid:{count:mid.count,first:Math.min(...mid.indices),last:Math.max(...mid.indices)},cards:{count:cards.count,height:cards.height},reversed:reversed.indices.slice(0,5),reduced:reduced.count,pane:pCount,browse:bCount}))
    if(width===375) await page.screenshot({path:'artifacts/virtualization-fixture-mobile.png'})
    if(width===1440) await page.screenshot({path:'artifacts/virtualization-fixture-desktop.png'})
  }catch(e){failures++;console.log(JSON.stringify({width,pass:false,error:String(e),pageerrors:errors}))}
  await page.close()
}
await browser.close()
if(failures)process.exit(1)
